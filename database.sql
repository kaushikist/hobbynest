-- Publish a class with its lessons and lectures in ONE step.
-- If anything fails, nothing is saved (no half-created courses).
-- Runs with the caller's permissions, so all the policies above still apply.
create or replace function public.publish_course(
    p_course   jsonb,
    p_lessons  jsonb default '[]'::jsonb,
    p_lectures jsonb default '[]'::jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    new_course_id bigint;
    item jsonb;
    position_no integer;
begin
    if auth.uid() is null then
        raise exception 'Your session has expired. Please log in again.';
    end if;

    if not public.is_educator() then
        raise exception 'Only educators can publish classes.';
    end if;

    if coalesce(trim(p_course->>'title'), '') = '' then
        raise exception 'Please enter a class name.';
    end if;

    insert into public.courses (
        educator_id, title, description, category, level, duration, fee,
        capacity, location, schedule, teaching_format, certificate,
        thumbnail, published
    )
    values (
        auth.uid(),
        trim(p_course->>'title'),
        nullif(trim(coalesce(p_course->>'description', '')), ''),
        nullif(p_course->>'category', ''),
        nullif(p_course->>'level', ''),
        nullif(trim(coalesce(p_course->>'duration', '')), ''),
        coalesce((p_course->>'fee')::numeric, 0),
        coalesce((p_course->>'capacity')::integer, 30),
        nullif(trim(coalesce(p_course->>'location', '')), ''),
        nullif(trim(coalesce(p_course->>'schedule', '')), ''),
        nullif(p_course->>'teaching_format', ''),
        coalesce((p_course->>'certificate')::boolean, false),
        nullif(p_course->>'thumbnail', ''),
        coalesce((p_course->>'published')::boolean, true)
    )
    returning id into new_course_id;

    position_no := 0;
    for item in select value from jsonb_array_elements(coalesce(p_lessons, '[]'::jsonb))
    loop
        position_no := position_no + 1;
        if coalesce(trim(item->>'title'), '') = '' then
            raise exception 'Lesson % needs a title.', position_no;
        end if;

        insert into public.lessons (course_id, title, description, duration, lesson_order, lesson_type)
        values (
            new_course_id,
            trim(item->>'title'),
            nullif(trim(coalesce(item->>'description', '')), ''),
            nullif(trim(coalesce(item->>'duration', '')), ''),
            position_no,
            coalesce(nullif(item->>'lesson_type', ''), 'video')
        );
    end loop;

    position_no := 0;
    for item in select value from jsonb_array_elements(coalesce(p_lectures, '[]'::jsonb))
    loop
        position_no := position_no + 1;
        if coalesce(trim(item->>'title'), '') = '' or coalesce(trim(item->>'youtube_url'), '') = '' then
            raise exception 'Lecture % needs both a title and a YouTube URL.', position_no;
        end if;
        if trim(item->>'youtube_url') !~* '^https?://([a-z0-9-]+\.)?(youtube\.com|youtu\.be)/' then
            raise exception 'Lecture % must use a YouTube link (youtube.com or youtu.be).', position_no;
        end if;

        insert into public.course_lectures (course_id, title, youtube_url, duration, lecture_order)
        values (
            new_course_id,
            trim(item->>'title'),
            trim(item->>'youtube_url'),
            nullif(trim(coalesce(item->>'duration', '')), ''),
            position_no
        );
    end loop;

    return new_course_id;
end;
$$;

-- Update a class you own: course details, lessons and lectures in ONE step.
-- Lessons/lectures sent with an "id" are updated in place (so learner progress
-- on them is kept); ones without an id are added; ones left out are removed.
create or replace function public.update_course(
    p_course_id bigint,
    p_course    jsonb,
    p_lessons   jsonb default '[]'::jsonb,
    p_lectures  jsonb default '[]'::jsonb
)
returns bigint
language plpgsql
security invoker
set search_path = public
as $$
declare
    item jsonb;
    position_no integer;
    keep_ids bigint[];
begin
    if auth.uid() is null then
        raise exception 'Your session has expired. Please log in again.';
    end if;

    if not public.owns_course(p_course_id) then
        raise exception 'You can only edit your own classes.';
    end if;

    if coalesce(trim(p_course->>'title'), '') = '' then
        raise exception 'Please enter a class name.';
    end if;

    update public.courses set
        title           = trim(p_course->>'title'),
        description     = nullif(trim(coalesce(p_course->>'description', '')), ''),
        category        = nullif(p_course->>'category', ''),
        level           = nullif(p_course->>'level', ''),
        duration        = nullif(trim(coalesce(p_course->>'duration', '')), ''),
        fee             = coalesce((p_course->>'fee')::numeric, 0),
        capacity        = coalesce((p_course->>'capacity')::integer, 30),
        location        = nullif(trim(coalesce(p_course->>'location', '')), ''),
        schedule        = nullif(trim(coalesce(p_course->>'schedule', '')), ''),
        teaching_format = nullif(p_course->>'teaching_format', ''),
        certificate     = coalesce((p_course->>'certificate')::boolean, false),
        -- a new thumbnail URL replaces the old one; leaving it out keeps the old one
        thumbnail       = coalesce(nullif(p_course->>'thumbnail', ''), thumbnail),
        published       = coalesce((p_course->>'published')::boolean, published)
    where id = p_course_id;

    -- Lessons
    select coalesce(array_agg((value->>'id')::bigint), '{}')
      into keep_ids
      from jsonb_array_elements(coalesce(p_lessons, '[]'::jsonb))
     where nullif(value->>'id', '') is not null;

    delete from public.lessons
     where course_id = p_course_id and not (id = any(keep_ids));

    position_no := 0;
    for item in select value from jsonb_array_elements(coalesce(p_lessons, '[]'::jsonb))
    loop
        position_no := position_no + 1;
        if coalesce(trim(item->>'title'), '') = '' then
            raise exception 'Lesson % needs a title.', position_no;
        end if;

        if nullif(item->>'id', '') is not null then
            update public.lessons set
                title        = trim(item->>'title'),
                description  = nullif(trim(coalesce(item->>'description', '')), ''),
                duration     = nullif(trim(coalesce(item->>'duration', '')), ''),
                lesson_type  = coalesce(nullif(item->>'lesson_type', ''), 'video'),
                lesson_order = position_no
            where id = (item->>'id')::bigint and course_id = p_course_id;
        else
            insert into public.lessons (course_id, title, description, duration, lesson_order, lesson_type)
            values (
                p_course_id,
                trim(item->>'title'),
                nullif(trim(coalesce(item->>'description', '')), ''),
                nullif(trim(coalesce(item->>'duration', '')), ''),
                position_no,
                coalesce(nullif(item->>'lesson_type', ''), 'video')
            );
        end if;
    end loop;

    -- Lectures
    select coalesce(array_agg((value->>'id')::bigint), '{}')
      into keep_ids
      from jsonb_array_elements(coalesce(p_lectures, '[]'::jsonb))
     where nullif(value->>'id', '') is not null;

    delete from public.course_lectures
     where course_id = p_course_id and not (id = any(keep_ids));

    position_no := 0;
    for item in select value from jsonb_array_elements(coalesce(p_lectures, '[]'::jsonb))
    loop
        position_no := position_no + 1;
        if coalesce(trim(item->>'title'), '') = '' or coalesce(trim(item->>'youtube_url'), '') = '' then
            raise exception 'Lecture % needs both a title and a YouTube URL.', position_no;
        end if;
        if trim(item->>'youtube_url') !~* '^https?://([a-z0-9-]+\.)?(youtube\.com|youtu\.be)/' then
            raise exception 'Lecture % must use a YouTube link (youtube.com or youtu.be).', position_no;
        end if;

        if nullif(item->>'id', '') is not null then
            update public.course_lectures set
                title         = trim(item->>'title'),
                youtube_url   = trim(item->>'youtube_url'),
                duration      = nullif(trim(coalesce(item->>'duration', '')), ''),
                lecture_order = position_no
            where id = (item->>'id')::bigint and course_id = p_course_id;
        else
            insert into public.course_lectures (course_id, title, youtube_url, duration, lecture_order)
            values (
