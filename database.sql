-- People you can start a conversation with, and why (for the "New message" list).
create or replace function public.my_contacts()
returns table (user_id uuid, full_name text, profile_image text, headline text, role text, reason text)
language sql
stable
security definer
set search_path = public
as $$
    with links as (
        select c.educator_id as uid, 'Your educator · ' || c.title as reason, 1 as rank
        from public.enrollments e join public.courses c on c.id = e.course_id
        where e.learner_id = auth.uid()
        union all
        select e.learner_id, 'Your student · ' || c.title, 1
        from public.enrollments e join public.courses c on c.id = e.course_id
        where c.educator_id = auth.uid()
        union all
        select m.created_by, 'Meetup host · ' || m.title, 2
        from public.meetup_registrations r join public.meetups m on m.id = r.meetup_id
        where r.user_id = auth.uid()
        union all
        select r.user_id, 'Going to your meetup · ' || m.title, 2
        from public.meetup_registrations r join public.meetups m on m.id = r.meetup_id
        where m.created_by = auth.uid()
        union all
        select sender_id, 'Messaged you', 3
        from public.messages where receiver_id = auth.uid()
    )
    select distinct on (p.id) p.id, p.full_name, p.profile_image, p.headline, p.role, l.reason
    from links l join public.profiles p on p.id = l.uid
    where l.uid <> auth.uid()
    order by p.id, l.rank, l.reason;
$$;

