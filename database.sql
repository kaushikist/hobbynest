-- =====================================================================
-- 11. PHOTO STORAGE (Supabase Storage)
--    avatars        → profile pictures, saved as  <your user id>/<file>
--    course-images  → class thumbnails, saved as  <educator id>/<file>
--    social-posts   → photos in Socials posts, saved as  <your user id>/<file>
--    Anyone can view the images (public buckets); people can only add,
--    replace or delete files inside their own folder.
-- =====================================================================

do $$
begin
    if not exists (select 1 from information_schema.schemata where schema_name = 'storage') then
        raise notice 'Storage is not available in this database — skipping photo buckets.';
        return;
    end if;

    insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    values
        ('avatars', 'avatars', true, 2097152, array['image/jpeg', 'image/png', 'image/webp']),
        ('course-images', 'course-images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp']),
        ('social-posts', 'social-posts', true, 5242880, array['image/jpeg', 'image/png', 'image/webp'])
    on conflict (id) do update
        set public = excluded.public,
            file_size_limit = excluded.file_size_limit,
            allowed_mime_types = excluded.allowed_mime_types;

    drop policy if exists "hobbynest_avatars_select_own" on storage.objects;
    drop policy if exists "hobbynest_course_images_select_own" on storage.objects;
    drop policy if exists "hobbynest_avatars_insert_own" on storage.objects;
    drop policy if exists "hobbynest_avatars_update_own" on storage.objects;
    drop policy if exists "hobbynest_avatars_delete_own" on storage.objects;
    drop policy if exists "hobbynest_course_images_insert_educator" on storage.objects;
    drop policy if exists "hobbynest_course_images_update_own" on storage.objects;
    drop policy if exists "hobbynest_course_images_delete_own" on storage.objects;
    drop policy if exists "hobbynest_social_posts_select_own" on storage.objects;
    drop policy if exists "hobbynest_social_posts_insert_own" on storage.objects;
    drop policy if exists "hobbynest_social_posts_delete_own" on storage.objects;

    -- Storage needs "see your own files" to replace or delete them.
    -- (Viewing images on the site uses public links and doesn't need this.)
    create policy "hobbynest_avatars_select_own" on storage.objects
        for select to authenticated
        using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
    create policy "hobbynest_course_images_select_own" on storage.objects
        for select to authenticated
        using (bucket_id = 'course-images' and (storage.foldername(name))[1] = auth.uid()::text);

    create policy "hobbynest_avatars_insert_own" on storage.objects
        for insert to authenticated
        with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
    create policy "hobbynest_avatars_update_own" on storage.objects
        for update to authenticated
        using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text)
        with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);
    create policy "hobbynest_avatars_delete_own" on storage.objects
        for delete to authenticated
        using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

    create policy "hobbynest_course_images_insert_educator" on storage.objects
        for insert to authenticated
        with check (bucket_id = 'course-images'
                    and (storage.foldername(name))[1] = auth.uid()::text
                    and public.is_educator());
    create policy "hobbynest_course_images_update_own" on storage.objects
        for update to authenticated
        using (bucket_id = 'course-images' and (storage.foldername(name))[1] = auth.uid()::text)
        with check (bucket_id = 'course-images' and (storage.foldername(name))[1] = auth.uid()::text);
    create policy "hobbynest_course_images_delete_own" on storage.objects
        for delete to authenticated
        using (bucket_id = 'course-images' and (storage.foldername(name))[1] = auth.uid()::text);

    create policy "hobbynest_social_posts_select_own" on storage.objects
        for select to authenticated
        using (bucket_id = 'social-posts' and (storage.foldername(name))[1] = auth.uid()::text);
    create policy "hobbynest_social_posts_insert_own" on storage.objects
        for insert to authenticated
        with check (bucket_id = 'social-posts' and (storage.foldername(name))[1] = auth.uid()::text);
    create policy "hobbynest_social_posts_delete_own" on storage.objects
        for delete to authenticated
        using (bucket_id = 'social-posts' and (storage.foldername(name))[1] = auth.uid()::text);

exception
    when insufficient_privilege then
        raise notice 'Could not set up photo storage rules automatically (%). Everything else was applied.', sqlerrm;
end;
$$;


