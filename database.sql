-- 13. ACCOUNT DELETION, NOTIFICATIONS AND EMAIL LOG
-- =====================================================================

-- 13a. Make sure deleting a user can never be blocked by an old foreign key.
--   Tables that existed before this file was first run may have foreign keys
--   WITHOUT "on delete cascade" ("add column if not exists" never fixes an
--   existing column). Supabase then refuses to delete the user with
--   "Database error deleting user". Every foreign key that points at a user
--   (auth.users / profiles) or at a class, lesson, post or meetup is rebuilt
--   here with ON DELETE CASCADE. Keys that already cascade or SET NULL are kept.
do $$
declare
    fk record;
    new_def text;
begin
    for fk in
        select con.conname,
               con.conrelid::regclass as tbl,
               pg_get_constraintdef(con.oid) as def
        from pg_constraint con
        where con.contype = 'f'
          and con.connamespace = 'public'::regnamespace
          and con.confdeltype in ('a', 'r')          -- NO ACTION / RESTRICT
          and con.confrelid in (
              'auth.users'::regclass, 'public.profiles'::regclass, 'public.courses'::regclass,
              'public.lessons'::regclass, 'public.social_posts'::regclass, 'public.meetups'::regclass
          )
    loop
        new_def := regexp_replace(fk.def, '\s+ON DELETE\s+(NO ACTION|RESTRICT)', '', 'i') || ' ON DELETE CASCADE';
        raise notice 'Making %.% cascade on delete', fk.tbl, fk.conname;
        execute format('alter table %s drop constraint %I', fk.tbl, fk.conname);
        execute format('alter table %s add constraint %I %s', fk.tbl, fk.conname, new_def);
    end loop;
end;
$$;

