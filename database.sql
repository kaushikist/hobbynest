-- 13d. When an educator schedules (or cancels) a live session for a class,
--   every enrolled learner gets it straight in their Messages inbox, so it
--   shows up with an unread badge — not only on the Schedule page.
create or replace function public.notify_session_learners()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    s record;
    note text;
    when_text text;
begin
    if tg_op = 'DELETE' then
        s := old;
        -- Only direct cancellations of future sessions. Sessions removed because
        -- the whole class or educator account was deleted are skipped (depth > 1).
        if pg_trigger_depth() > 1 or s.session_date < now() then
            return old;
        end if;
    else
        s := new;
    end if;

    if s.course_id is null then
        return coalesce(new, old);   -- "open to everyone" sessions only appear on Schedule
    end if;

    when_text := to_char(s.session_date at time zone 'Asia/Kolkata', 'Dy, DD Mon YYYY "at" HH12:MI AM') || ' IST';

    if tg_op = 'DELETE' then
        note := '❌ Live session cancelled: ' || s.title || E'\n' || when_text;
    else
        note := '📅 New live session: ' || s.title || E'\n' || when_text
             || coalesce(E'\n' || nullif(trim(s.description), ''), '')
             || coalesce(E'\nJoin link: ' || s.meeting_link, E'\nThe join link will be shared before the session.')
             || E'\nIt is also on your Schedule page.';
    end if;

    insert into public.messages (sender_id, receiver_id, message, kind)
    select s.educator_id, e.learner_id, left(note, 2000), 'session'
    from public.enrollments e
    where e.course_id = s.course_id
      and e.learner_id <> s.educator_id;

    return coalesce(new, old);
end;
$$;

