-- =====================================================================
-- 14. DELETE MY ACCOUNT (works with just this file — no Edge Function needed)
--     The app calls  supabaseClient.rpc("delete_my_account").
--     It deletes ONLY the logged-in user. Their profile, classes, enrollments,
--     progress, messages, posts and meetups are removed by ON DELETE CASCADE
--     (section 13a makes sure every foreign key cascades).
-- =====================================================================

create or replace function public.delete_my_account()
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    me uuid := auth.uid();
begin
    if me is null then
        raise exception 'Your session has expired. Please log in again.';
    end if;

    -- Older projects: uploaded files point at their owner, which would block
    -- deleting the user. Detach them (the app removes the files themselves first).
    begin
        execute 'update storage.objects set owner = null where owner = $1' using me;
    exception when others then
        null;   -- no storage schema / column / permission: nothing to detach
    end;
    begin
        execute 'update storage.objects set owner_id = null where owner_id = $1' using me::text;
    exception when others then
        null;
    end;

    delete from auth.users where id = me;
    return true;
end;
$$;

revoke execute on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;


