-- Older hand-made tables may have extra REQUIRED columns the app never fills
-- (e.g. progress.course_id, sessions.start_time, user_id). Those would make every
-- insert from the app fail, so any required column that is not part of the app's
-- schema (and has no default) is made optional. Your data in them is kept.
do $$
declare
    col record;
begin
    for col in
        select c.table_name, c.column_name
        from information_schema.columns c
        where c.table_schema = 'public'
          and c.table_name in ('profiles', 'courses', 'lessons', 'course_lectures', 'enrollments',
                               'progress', 'saved_courses', 'sessions', 'messages', 'reviews',
                               'social_posts', 'post_likes', 'post_comments',
                               'meetups', 'meetup_registrations')
          and c.is_nullable = 'NO'
          and c.column_default is null
          and c.is_identity = 'NO'
          and c.column_name <> 'id'
          and (c.table_name || '.' || c.column_name) not in (
              'profiles.role',
              'courses.educator_id', 'courses.title',
              'lessons.course_id', 'lessons.title',
              'course_lectures.course_id', 'course_lectures.title', 'course_lectures.youtube_url',
              'enrollments.learner_id', 'enrollments.course_id',
              'progress.learner_id', 'progress.lesson_id',
              'saved_courses.learner_id', 'saved_courses.course_id',
              'sessions.educator_id', 'sessions.title', 'sessions.session_date',
              'messages.sender_id', 'messages.receiver_id', 'messages.message',
              'reviews.learner_id', 'reviews.course_id', 'reviews.rating',
              'social_posts.user_id',
              'post_likes.post_id', 'post_likes.user_id',
              'post_comments.post_id', 'post_comments.user_id', 'post_comments.comment',
              'meetups.created_by', 'meetups.title', 'meetups.starts_at',
              'meetup_registrations.meetup_id', 'meetup_registrations.user_id'
          )
          -- primary-key columns must stay required
          and not exists (
              select 1
              from information_schema.table_constraints tc
              join information_schema.key_column_usage k
                on k.constraint_name = tc.constraint_name and k.table_schema = tc.table_schema
              where tc.table_schema = 'public' and tc.table_name = c.table_name
                and tc.constraint_type = 'PRIMARY KEY' and k.column_name = c.column_name
          )
    loop
        raise notice 'Making %.% optional (not used by the app)', col.table_name, col.column_name;
        execute format('alter table public.%I alter column %I drop not null', col.table_name, col.column_name);
    end loop;
end;
$$;

