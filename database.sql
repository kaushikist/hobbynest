-- Full classes can't take more learners (checked inside the database).
create or replace function public.check_course_capacity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    max_seats integer;
    taken integer;
begin
    -- Lock the course row so two learners can't take the last seat at once.
    select capacity into max_seats from public.courses where id = new.course_id for update;
    select count(*) into taken from public.enrollments where course_id = new.course_id;
    if max_seats is not null and taken >= max_seats then
        raise exception 'Sorry, this class is full.';
    end if;
    return new;
end;
$$;

