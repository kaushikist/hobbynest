-- Who you're allowed to message: people you share a class with (educator ↔ student),
-- a meetup you host or joined (host ↔ attendee), or anyone who messaged you first.
create or replace function public.can_message(p_other uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select p_other is not null and p_other <> auth.uid() and (
        exists (
            select 1 from public.enrollments e
            join public.courses c on c.id = e.course_id
            where (e.learner_id = auth.uid() and c.educator_id = p_other)
               or (e.learner_id = p_other and c.educator_id = auth.uid())
        )
        or exists (
            select 1 from public.meetup_registrations r
            join public.meetups m on m.id = r.meetup_id
            where (r.user_id = auth.uid() and m.created_by = p_other)
               or (r.user_id = p_other and m.created_by = auth.uid())
        )
        or exists (
            select 1 from public.messages
            where sender_id = p_other and receiver_id = auth.uid()
        )
    );
$$;

