create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    requested_role text := new.raw_user_meta_data->>'role';
begin
    insert into public.profiles (id, full_name, email, role, city)
    values (
        new.id,
        coalesce(new.raw_user_meta_data->>'full_name', ''),
        new.email,
        case when requested_role in ('learner', 'educator') then requested_role else 'learner' end,
        nullif(trim(coalesce(new.raw_user_meta_data->>'city', '')), '')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row
    execute procedure public.handle_new_user();


-- =====================================================================
-- 6. PROFILE PROTECTION
--    • Role can be chosen during onboarding, then it is locked.
--    • Onboarding cannot be "un-completed" (that would unlock the role).
--    • id, email and created_at cannot be edited by the user.
--    Changes made from the SQL Editor (no logged-in user) are not blocked,
--    so you can still fix a user's role manually as the admin.
-- =====================================================================

create or replace function public.protect_profile_fields()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    if auth.uid() is null then
        return new;   -- admin / SQL Editor
    end if;

    if new.id is distinct from old.id then
        raise exception 'Profile id cannot be changed.';
    end if;

    new.email := old.email;
    new.created_at := old.created_at;

    if old.onboarding_complete then
        if new.role is distinct from old.role then
            raise exception 'Your role is locked after onboarding.';
        end if;
        if new.onboarding_complete is distinct from true then
            raise exception 'Onboarding cannot be reset.';
        end if;
    end if;

    return new;
end;
$$;

